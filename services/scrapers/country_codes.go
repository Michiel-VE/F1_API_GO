func normalizeCountry(raw string) string {
	trimmed := strings.TrimSpace(raw)
	if trimmed == "" {
		return ""
	}
	key := strings.ToLower(trimmed)
	if canonical, ok := canonicalCountryMap[key]; ok {
		return canonical
	}
	return trimmed
}

func getCountryCode(country string) string {
	canonical := normalizeCountry(country)
	if canonical == "" {
		return ""
	}
	if code, ok := countryToAlpha3[canonical]; ok {
		return code
	}
	return ""
}
